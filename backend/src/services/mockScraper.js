'use strict';

/**
 * Mock scraper (SCRAPER_MODE=mock).
 *
 * Runs entirely inside the Node process: no USdirectory requests, no Python
 * service required. It produces deterministic, clearly synthetic demo leads
 * (reserved 555-01xx phone numbers, @example.com addresses and non-resolvable
 * *.example.com websites) so the whole product can be demoed and tested
 * offline. Every lead is flagged demoData=true.
 */

const { parseLocation } = require('./usStates');

const NAME_PREFIXES = [
  'Cedar Ridge', 'Summit', 'Blue Sky', 'Ironclad', 'Evergreen', 'Pioneer',
  'Northgate', 'Silverline', 'Apex', 'Fairview', 'Brightstone', 'Highpoint',
  'Oakwood', 'Juniper', 'Copper Creek', 'Lakeside', 'Redstone', 'Westbrook',
  'Hearthstone', 'Stonebridge', 'Clearwater', 'Meadowlark', 'Trinity',
  'Riverside', 'Maplewood',
];
const GENERIC_SUFFIXES = ['Group', 'Solutions', 'Services', 'Company', 'Partners', 'Industries'];
const STREET_NAMES = [
  'Main St', 'Oak Ave', 'Washington St', 'Maple Ave', 'Industrial Way',
  'Commerce Dr', 'Cedar St', '3rd Ave', 'Sunset Blvd', 'Lincoln St',
  'Brookside Rd', 'Park Ave',
];
const DEMO_AREA_CODES = ['212', '303', '312', '404', '480', '503', '617', '702', '916', '971'];
const SERVICE_ACTIONS = ['Consultation', 'Estimates', 'Repairs', 'Maintenance', 'Installation'];

/** Small deterministic PRNG so the same request always yields the same leads. */
function mulberry32(seed) {
  let state = seed >>> 0;
  return function next() {
    state += 0x6d2b79f5;
    let t = state;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function hashSeed(category, location) {
  const input = `${String(category).toLowerCase()}|${String(location).toLowerCase()}`;
  let hash = 2166136261;
  for (let i = 0; i < input.length; i += 1) {
    hash ^= input.charCodeAt(i);
    hash = Math.imul(hash, 16777619);
  }
  return hash >>> 0;
}

const pick = (random, list) => list[Math.floor(random() * list.length)];
const slugifyName = (name) => name.replace(/[^A-Za-z0-9]+/g, '-').replace(/^-|-$/g, '');

function buildLeads({ category, location, maxLeads, enrichment = true }) {
  const parsed = parseLocation(location);
  const city = parsed.city || 'Springfield';
  const stateName = parsed.state || 'Oregon';
  const stateCode = parsed.stateAbbr || 'OR';
  const random = mulberry32(hashSeed(category, location));
  const services = SERVICE_ACTIONS.map((action) => `${category} ${action}`);
  const usedNames = new Set();
  const leads = [];

  for (let index = 0; index < maxLeads; index += 1) {
    const prefix = pick(random, NAME_PREFIXES);
    const suffix = random() < 0.55 ? category : `${category} ${pick(random, GENERIC_SUFFIXES)}`;
    let name = `${prefix} ${suffix}`;
    if (usedNames.has(name)) name = `${name} ${(index % 97) + 1}`;
    usedNames.add(name);

    const slug = slugifyName(name).toLowerCase();
    const street = `${100 + Math.floor(random() * 9800)} ${pick(random, STREET_NAMES)}`;
    const zip = String(10000 + Math.floor(random() * 89999));

    const phone = random() < 0.88
      ? `(${pick(random, DEMO_AREA_CODES)}) 555-01${String(Math.floor(random() * 100)).padStart(2, '0')}`
      : null;
    const email = random() < 0.62 ? `info@${slug}.example.com` : null;
    const website = enrichment && random() < 0.7 ? `https://www.${slug}.example.com` : null;

    leads.push({
      businessName: name,
      category,
      description:
        `${name} is a ${category.toLowerCase()} provider serving ${city}, ${stateName} and the ` +
        'surrounding area. Listed in the public directory with services such as ' +
        `${services.slice(0, 3).map((service) => service.toLowerCase()).join(', ')}.`,
      address: `${street}, ${city}, ${stateCode} ${zip}`,
      city,
      state: stateCode,
      zip,
      phone,
      email,
      website,
      source: 'usdirectory',
      sourceUrl:
        `https://usdirectory.com/${slugifyName(name)}-${city.replace(/ /g, '-')}-${stateCode}-` +
        `${100000 + index * 7}`,
      sourceId: String(100000 + index * 7),
      contactPageUrl: null,
      publicEmails: email ? [email] : [],
      publicPhones: phone ? [phone] : [],
      services,
      emailStatus: email ? 'valid' : 'unknown',
      enrichmentStatus: 'not_attempted',
      demoData: true,
      notes: ['Synthetic demo data generated by mock mode - no real business is represented.'],
      scrapedAt: new Date(),
    });
  }
  return leads;
}

/**
 * Simulate website enrichment: for listings that publish a website we "visit"
 * the contact page and pick up whatever the site displays publicly.
 */
function simulateEnrichment(leads) {
  let enriched = 0;
  let failed = 0;

  leads.forEach((lead, index) => {
    if (!lead.website) {
      lead.enrichmentStatus = 'no_website';
      return;
    }
    if (index % 11 === 0) {
      // Simulate a website that could not be read (offline / access restricted).
      lead.enrichmentStatus = 'failed';
      lead.notes.push('Website enrichment failed: the site could not be read.');
      failed += 1;
      return;
    }

    const slug = lead.website.replace('https://www.', '').replace('.example.com', '');
    const contactUrl = `${lead.website}/contact`;
    lead.contactPageUrl = contactUrl;
    lead.enrichmentSources = [contactUrl];

    if (!lead.email) {
      const found = `office@${slug}.example.com`;
      lead.email = found;
      lead.publicEmails = Array.from(new Set([...lead.publicEmails, found]));
      lead.emailStatus = 'valid';
    }
    if (!lead.phone) {
      const digits = `50355501${String((index % 90) + 9).padStart(2, '0').slice(-2)}`;
      lead.phone = `+1${digits}`;
      lead.publicPhones = Array.from(new Set([...lead.publicPhones, lead.phone]));
    }

    lead.enrichmentStatus = 'completed';
    lead.notes.push('Checked 2 public page(s) on the business website; 1 contained contact details.');
    enriched += 1;
  });

  return { enriched, failed };
}

/**
 * Produce leads for a job, reporting progress as it goes.
 * @param {object} options
 * @param {(update: object) => Promise<void>} [options.onProgress]
 */
async function scrape({
  category,
  location,
  maxLeads = 100,
  enrichment = true,
  onProgress = async () => {},
}) {
  const parsed = parseLocation(location);
  await onProgress({
    stage: 'searching',
    percent: 10,
    message: `Mock mode: simulating a ${category} search in ${location}`,
    leadsFound: 0,
  });

  const rawLeads = buildLeads({ category, location, maxLeads, enrichment });
  const pages = Math.max(1, Math.ceil(rawLeads.length / 25));
  for (let page = 1; page <= pages; page += 1) {
    await onProgress({
      stage: 'discovering',
      percent: 15 + Math.round((page / pages) * 35),
      message: `Discovered ${Math.min(rawLeads.length, page * 25)} listings on ${page} page(s)`,
      leadsFound: Math.min(rawLeads.length, page * 25),
    });
  }

  await onProgress({
    stage: 'extracting',
    percent: 65,
    message: `Extracted ${rawLeads.length} business profiles`,
    leadsFound: rawLeads.length,
  });

  let stats = { enriched: 0, failed: 0 };
  if (enrichment) {
    await onProgress({
      stage: 'enriching',
      percent: 85,
      message: 'Enriching from business websites',
      leadsFound: rawLeads.length,
    });
    stats = simulateEnrichment(rawLeads);
  }

  await onProgress({
    stage: 'done',
    percent: 98,
    message: `${rawLeads.length} leads ready`,
    leadsFound: rawLeads.length,
  });

  return {
    mode: 'mock',
    source: 'usdirectory',
    category,
    location,
    requested: maxLeads,
    leads: rawLeads,
    stats: {
      pagesFetched: pages,
      profilesFetched: rawLeads.length,
      profilesParsed: rawLeads.length,
      enriched: stats.enriched,
      enrichmentFailed: stats.failed,
      blocked: false,
    },
    warnings: [
      'Mock mode is enabled: these are synthetic demo leads and do not represent real businesses.',
    ],
    resolvedLocation: parsed,
  };
}

module.exports = { buildLeads, hashSeed, mulberry32, scrape, simulateEnrichment };
